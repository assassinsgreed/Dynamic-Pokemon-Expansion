"""Where to find items and TMs, from the item tables of the Pokémon Amethyst feature list (Google Doc).

items.csv and machines.csv are generated by `python -m tools.dexpage.items <feature-list.docx>` from a
File → Download → .docx export of that doc. The importer needs python-docx; building the page does not."""

import csv
import sys
from pathlib import Path

ITEMS_CSV = Path(__file__).with_name("items.csv")
MACHINES_CSV = Path(__file__).with_name("machines.csv")
TUTORS_CSV = Path(__file__).with_name("tutors.csv")

# Item tables are found by their first header cell; the heading above each table names the category.
ITEM_TABLE_HEADERS = {"Item", "Berry", "Incense", "Consumable", "Mega Stone"}
# Short names in some tables: "Cheri" is the Cheri Berry, "Lax" the Lax Incense
NAME_SUFFIX = {"Berries": " Berry", "Breeding": " Incense"}


def _lines(text: str) -> list[str]:
    return [line.strip() for line in text.splitlines() if line.strip()]


def _split_variants(name: str) -> list[str]:
    """"Red/Yellow/Pink/Purple Nectar" is four items sharing one row."""
    if "/" not in name or " " not in name:
        return [name]
    variants, suffix = name.rsplit(" ", 1)
    return [f"{v.strip()} {suffix}" for v in variants.split("/")]


def load_items(path: Path = ITEMS_CSV) -> list[dict]:
    with path.open(encoding="utf-8", newline="") as f:
        return [{"name": r["Item"], "category": r["Category"], "where": _lines(r["Where"]), "use": r["Use"]}
                for r in csv.DictReader(f)]


def load_machine_locations(path: Path = MACHINES_CSV) -> dict[tuple[str, int], dict]:
    with path.open(encoding="utf-8", newline="") as f:
        return {(r["Kind"], int(r["Number"])): {"move": r["Move"], "where": _lines(r["Where"]), "requires": r["Requires"]}
                for r in csv.DictReader(f)}


def load_tutors(path: Path = TUTORS_CSV) -> list[dict]:
    with path.open(encoding="utf-8", newline="") as f:
        return [{"kind": r["Kind"], "where": r["Where"], "move": r["Move"], "note": r["Note"]} for r in csv.DictReader(f)]


def import_docx(docx_path: Path) -> None:
    import docx  # optional dependency, only for re-importing the feature list
    from docx.oxml.ns import qn

    document = docx.Document(str(docx_path))
    items, machines, tutors = [], [], []
    heading, table_index = None, 0
    for el in document.element.body.iterchildren():
        if el.tag == qn("w:p"):
            style = el.find(".//" + qn("w:pStyle"))
            text = "".join(t.text or "" for t in el.iter(qn("w:t"))).strip()
            if style is not None and style.get(qn("w:val")).startswith("Heading") and text:
                heading = text
        elif el.tag == qn("w:tbl"):
            table = document.tables[table_index]
            table_index += 1
            header = [c.text.strip() for c in table.rows[0].cells]
            rows = [[c.text.strip() for c in r.cells] for r in table.rows[1:]]
            if header == ["Where", "Moves", "Cost"]:
                # Regular tutors: a town, its move list, and the price; a second line under the town is a condition
                for r in rows:
                    where, *condition = _lines(r[0])
                    note = " · ".join([r[2], *[c.strip("()") for c in condition]])
                    tutors.extend(["Regular", where, move, note] for move in _lines(r[1]))
            elif header == ["Where", "Move", "Requirement"]:
                for r in rows:
                    tutors.append(["Special", r[0], r[1], " ".join(_lines(r[2]))])
            elif header[0] in ("TM #", "HM #"):
                kind = header[0][:2]
                for r in rows:
                    if r[0].isdigit():
                        machines.append([kind, r[0], r[1], r[2], r[3] if len(r) > 3 else ""])
            elif header[:2] in (["Prize", "Coin Cost"], ["Chip Cost", "Item"], ["Prize", "Chance to Find"]):
                # Prize tables: the item is obtainable here, at a price or a chance
                for r in rows:
                    name, detail = (r[1], r[0]) if header[0] == "Chip Cost" else (r[0], r[1])
                    where = {"Coin Cost": f"Daimyn City Game Corner ({detail} coins)",
                             "Item": f"PokeChip Crusher ({detail} chips)",
                             "Chance to Find": f"Mining minigame ({detail})"}[header[1]]
                    for single in _split_variants(name):
                        items.append([single, "", where, ""])
            elif header[0] in ITEM_TABLE_HEADERS and len(header) >= 3 and header[1].startswith(("Where", "How")):
                for r in rows:
                    if r[0]:
                        # A second line in the name cell is a note, e.g. "Razor Claw" + "(Must hold @ night)"
                        name, *note = _lines(r[0])
                        use = "\n".join([*note, r[2]]) if note else r[2]
                        for single in _split_variants(name):
                            items.append([single + NAME_SUFFIX.get(heading, ""), heading, r[1], use])

    with ITEMS_CSV.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Item", "Category", "Where", "Use"])
        w.writerows(items)
    with MACHINES_CSV.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Kind", "Number", "Move", "Where", "Requires"])
        w.writerows(machines)
    with TUTORS_CSV.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Kind", "Where", "Move", "Note"])
        w.writerows(tutors)
    print(f"Wrote {len(items)} items, {len(machines)} TMs/HMs and {len(tutors)} tutor moves")


if __name__ == "__main__":
    import_docx(Path(sys.argv[1]))
